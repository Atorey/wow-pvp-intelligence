-- Quita un índice de character_snapshots que repetía lo que ya da otro.
--
-- idx_snapshots_character (character_id, captured_at desc) es de la migración
-- 0001, de antes de que hubiera brackets por spec. La 0002 añadió el único
-- (character_id, bracket, captured_at), que empieza por la misma columna, y
-- desde entonces toda lectura de snapshots por personaje filtra también por
-- bracket: la ingesta por cambio, el archivado, los agregados, la ficha. Lo que
-- busca solo por personaje —la cascada de la clave foránea cuando
-- eraseCharacters borra de characters— usa igual la primera columna del único.
--
-- El 23 de octubre de 2026 ocupaba 17,4 MB con 169 lecturas en toda su vida,
-- frente a más de 24 millones del único, con la base en 457 MB de una cuota de
-- 500. Y crecía con la tabla que más crece: cada inserción de snapshot pagaba
-- dos índices por personaje en vez de uno.
--
-- Un drop index sin concurrently bloquea la tabla el rato que tarda en soltar
-- el fichero, que es un instante: no reescribe nada.
drop index if exists idx_snapshots_character;
